/** Emit the KTX2 (Basis Universal) transcoder worker as a same-origin file.
 *
 *  Three.js normally builds this worker from a blob: URL, which inherits the page's Content
 *  Security Policy. The Emscripten transcoder constructs its bindings with `new Function`,
 *  which the page policy forbids. Served from its own URL, the worker carries its own narrow
 *  policy (see server/app.ts), so the page keeps `script-src 'self' 'wasm-unsafe-eval'`.
 *
 *  Writes public/basis/ktx2-worker.js and public/basis/basis_transcoder.wasm from the installed
 *  three version; run automatically before dev and build. */
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { KTX2Loader } from 'three/examples/jsm/loaders/KTX2Loader.js';

const require = createRequire(import.meta.url);
const root = fileURLToPath(new URL('../', import.meta.url));
const basis = dirname(require.resolve('three/examples/jsm/libs/basis/basis_transcoder.js'));
const out = join(root, 'public', 'basis');
mkdirSync(out, { recursive: true });
const fn = KTX2Loader.BasisWorker.toString();
const body = [
  '/* Generated by scripts/build-ktx2-worker.mjs from three; do not edit. */',
  '/* constants */',
  'let _EngineFormat = ' + JSON.stringify(KTX2Loader.EngineFormat),
  'let _EngineType = ' + JSON.stringify(KTX2Loader.EngineType),
  'let _TranscoderFormat = ' + JSON.stringify(KTX2Loader.TranscoderFormat),
  'let _BasisFormat = ' + JSON.stringify(KTX2Loader.BasisFormat),
  '/* basis_transcoder.js */',
  readFileSync(join(basis, 'basis_transcoder.js'), 'utf8'),
  '/* worker */',
  fn.substring(fn.indexOf('{') + 1, fn.lastIndexOf('}')),
].join('\n');
writeFileSync(join(out, 'ktx2-worker.js'), body);
copyFileSync(join(basis, 'basis_transcoder.wasm'), join(out, 'basis_transcoder.wasm'));
console.log(`ktx2 worker: ${body.length} bytes, wasm ${readFileSync(join(out, 'basis_transcoder.wasm')).length} bytes`);
